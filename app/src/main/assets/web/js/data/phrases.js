/** Puts phrases for the current rank first; the rest stay reachable. */
export function phrasesFor(group, rank) {
  if (group.all) return { main: group.all, other: [] };
  const main = group[rank] || [];
  const other = ['superior', 'peer', 'subordinate']
    .filter((r) => r !== rank)
    .flatMap((r) => group[r] || [])
    .filter((p, i, all) => !main.includes(p) && all.indexOf(p) === i);
  return { main, other };
}

/** {شما} becomes جناب‌عالی, سرکار عالی or شما depending on the recipient. */
export function fillPronoun(text, recipientName, rank) {
  const polite = /^\s*(سرکار|خانم)/.test(recipientName || '') ? 'سرکار عالی' : 'جناب‌عالی';
  return String(text).replace(/\{شما\}/g, rank === 'subordinate' ? 'شما' : polite);
}
