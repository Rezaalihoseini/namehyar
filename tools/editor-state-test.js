import assert from 'node:assert/strict';
import {restyleCell, resetCell, lookOfRun} from '../app/src/main/assets/web/js/restyle.js';
import {ocrMetrics} from './ocr-metrics.js';
import {recoverZeroAdvanceSpace} from '../app/src/main/assets/web/js/pdf-spacing.js';
const cell={paras:[{runs:[{text:'متن با اندازهٔ ارثی'}],over:{line:6,before:2}}]};
const original=structuredClone(cell);
restyleCell(cell,{size:10},5);
assert.ok(cell.paras[0].over.line>6);
restyleCell(cell,{size:5},5);
assert.deepEqual(cell,original);
assert.equal(lookOfRun(cell.paras[0].runs[0],{size:8}).size,8);
restyleCell(cell,{color:'C00000'},5);
restyleCell(cell,{size:9},5);
restyleCell(cell,{size:5},5);
assert.equal(cell.paras[0].runs[0].color,'C00000');
assert.equal(cell.paras[0].runs[0].size,undefined);
resetCell(cell);assert.deepEqual(cell,original);
assert.equal(ocrMetrics('ک ی ۱۲۳','ك ي 123').cer,0);
assert.equal(ocrMetrics('نامه نامه','نامه').wordRecall,.5);
assert.equal(ocrMetrics('نامه','نامه').cer,0);
assert.throws(()=>ocrMetrics('','متن'),/Empty/);
const advances = new Map([['ﻢ', .633789]]);
assert.equal(recoverZeroAdvanceSpace('ﻢ ',3.802734,6,advances),'ﻢ‌');
assert.equal(recoverZeroAdvanceSpace('ﻢ ',5.4,6,advances),'ﻢ ');
assert.equal(recoverZeroAdvanceSpace('ﻢ ',3.8,6,new Map()),'ﻢ ');
console.log('Editor state: inherited sizes, exact reset, retained colour and OCR metric checks passed');
